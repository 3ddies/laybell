// Each translation is its own module (lib/locales), required the first time that
// language is actually read — never at launch. English stays in this file: it is
// the fallback, so it is always needed.
//
// require, not import, is the whole point: a static import would be evaluated at
// startup and there would be nothing to defer. Metro still bundles all ten from
// these literal paths, so there is no network fetch and no async boundary — the
// first lookup in a language builds its dictionary, and later ones reuse it.
const LOADERS: Record<Exclude<Lang, 'en'>, () => Record<string, string>> = {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  es: () => require('./locales/es').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  fr: () => require('./locales/fr').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  de: () => require('./locales/de').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  pt: () => require('./locales/pt').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  it: () => require('./locales/it').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  ru: () => require('./locales/ru').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  zh: () => require('./locales/zh').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  ja: () => require('./locales/ja').default,
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  hi: () => require('./locales/hi').default,
};
const loaded: Partial<Record<Lang, Record<string, string>>> = { en };

/** The dictionary for a language, built on first use. English if it can't load. */
function dict(lang: Lang): Record<string, string> {
  const have = loaded[lang];
  if (have) return have;
  let d = en;
  try {
    d = LOADERS[lang as Exclude<Lang, 'en'>]?.() ?? en;
  } catch {
    d = en;
  }
  loaded[lang] = d;
  return d;
}

/**
 * Build a language's dictionary ahead of the screen that needs it — called when
 * the app restores the saved language at startup, so the first painted screen
 * doesn't do it mid-render (LanguageContext).
 */
export function preloadLang(lang: Lang): void {
  dict(lang);
}

// Look up a key in the active language; fall back to English, then the raw key
// (so a missing translation degrades gracefully rather than rendering blank).
// Supports {name} placeholders: translate(lang, 'hi', { name: 'Sam' }).
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let str = dict(lang)[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split('{' + k + '}').join(String(v));
    }
  }
  return str;
}

// ─── Module-level active language (for non-React code) ───────────────────────
// timeAgo, count-unit labels, and the shared data-list label helpers run outside
// the React tree, so they can't read LanguageContext. LanguageProvider keeps this
// singleton in sync on every change; `tg()` is the param-free translator they use.
// Components should still use the `t` from useTranslation() so they re-render on
// language change — this is only for plain helpers/formatters.
let _activeLang: Lang = DEFAULT_LANG;
export function setActiveLang(l: Lang): void { _activeLang = l; }
export function getActiveLang(): Lang { return _activeLang; }
export function tg(key: string, vars?: Record<string, string | number>): string {
  return translate(_activeLang, key, vars);
}

// Localized "{count} <unit>" with minimal one/other plural handling. The unit
// keys live under `count.<unit>.one` / `count.<unit>.other` ('{n} like' /
// '{n} likes'); {n} is the already-abbreviated number (e.g. "1.2k"). Languages
// without a singular/plural split just use the same value for both forms.
export function countLabel(unit: string, n?: number | null): string {
  const num = n ?? 0;
  const form = num === 1 ? 'one' : 'other';
  return tg(`count.${unit}.${form}`, { n: formatCount(num) });
}

// Best-effort device language with NO native module (expo-localization isn't a
// dependency, keeping this OTA-safe). Hermes ships Intl, so the resolved locale
// gives the language subtag; anything unsupported falls back to English. Not used
// as the default anymore (we default to English per onboarding), but kept for any
// future "match my device" option.
export function detectDeviceLang(): Lang {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale; // e.g. 'fr-FR'
    const code = locale.split('-')[0].toLowerCase();
    if (isLang(code)) return code;
  } catch {}
  return DEFAULT_LANG;
}
