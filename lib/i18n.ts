// App localization — a tiny, dependency-free i18n layer (no expo-localization,
// so it stays OTA-shippable with no native rebuild). The active language lives in
// LanguageContext (persisted to AsyncStorage); components read strings via the
// `t()` from useTranslation(). Adding a language = add an entry to LANGUAGES, a
// dictionary in lib/locales/<code>.ts and a line in LOADERS below; any key a
// translation is missing falls back to English, so a partial translation never
// shows a blank.
//
// Translation status: en/es/fr/de/pt/it are author-checked; zh/hi/ru/ja are
// AI-translated for common UI terms and SHOULD get a native-speaker pass before a
// store release. Adoption is incremental — only screens migrated to t() localize
// (currently Settings + onboarding welcome); others stay English until migrated.

import { formatCount } from './format';

export type Lang = 'en' | 'es' | 'fr' | 'de' | 'pt' | 'it' | 'ru' | 'zh' | 'ja' | 'hi';

// The picker list. `native` is the language's own name (what users see); `label`
// is its English name (a recognizable subtitle). Order = display order.
export const LANGUAGES: { code: Lang; native: string; label: string }[] = [
  { code: 'en', native: 'English',    label: 'English' },
  { code: 'es', native: 'Español',    label: 'Spanish' },
  { code: 'fr', native: 'Français',   label: 'French' },
  { code: 'de', native: 'Deutsch',    label: 'German' },
  { code: 'pt', native: 'Português',  label: 'Portuguese' },
  { code: 'it', native: 'Italiano',   label: 'Italian' },
  { code: 'ru', native: 'Русский',    label: 'Russian' },
  { code: 'zh', native: '中文',        label: 'Chinese (Simplified)' },
  { code: 'ja', native: '日本語',      label: 'Japanese' },
  { code: 'hi', native: 'हिन्दी',       label: 'Hindi' },
];

export const DEFAULT_LANG: Lang = 'en';

export function isLang(v: any): v is Lang {
  return typeof v === 'string' && LANGUAGES.some((l) => l.code === v);
}

